'use strict';
const test=require('node:test'),assert=require('node:assert/strict'),vm=require('node:vm'),fs=require('node:fs'),path=require('node:path');
const core=require('../assets/version-sync.js');
const source=fs.readFileSync(path.join(__dirname,'../assets/netlify.js'),'utf8');
const SITE={id:'id-123',name:'fc27-tracker',url:'https://fc27-tracker.netlify.app',hasPublished:true,deployId:'deploy-abc',publishedAt:'2026-11-17T02:10:44Z',versionStatus:'ok',metadata:{id:'',name:'FC 27 Ultimate Tracker',version:'1.75.4',releaseDate:'2026-11-16',changelog:[]}};
const flush=()=>new Promise(r=>setImmediate(r));
test('Netlify UI handles manual update, per-project opt-in, changelog and ignores rollback',async()=>{
  let site=structuredClone(SITE);
  const events={},store=new Map(),state={settings:{netlifyLinks:{}},deletedProjects:[],projects:[{id:'fc27-tracker',name:'FC 27 Ultimate Tracker',folder:'fc27-tracker',url:'',status:'Ativo',version:'v1.75.0'}],releases:[]};
  const document={addEventListener:(type,fn)=>{(events[type]??=[]).push(fn)},hidden:false,getElementById:()=>({value:'x'.repeat(64)})};
  const context={window:{HubVersionSync:core},document,localStorage:{getItem:key=>store.get(key)||null,setItem:(key,val)=>store.set(key,val)},fetch:async()=>({ok:true,json:async()=>({sites:[structuredClone(site)],total:1,nextOffset:null,checkedAt:'2026-11-17T10:00:00Z'})}),URL,Date,AbortSignal,confirm:()=>true,setInterval:()=>0};
  vm.runInNewContext(source,context);
  let saves=0;
  context.window.HubNetlify.init({state:()=>state,save:()=>saves++,compare:core.compare,refresh:()=>0});
  assert.match(context.window.HubNetlify.view(),/Conectar e sincronizar/);
  for(const fn of events.submit)fn({target:{id:'net-login'},preventDefault:()=>0});
  await flush();await flush();
  assert.match(context.window.HubNetlify.view(),/Atualizar catálogo para 1.75.4/);
  assert.equal(state.projects[0].version,'v1.75.0');
  for(const fn of events.click)await fn({target:{closest:()=>({dataset:{net:'update',site:'id-123'}})}});
  assert.equal(state.projects[0].version,'v1.75.4');
  assert.equal(state.releases.length,1);
  assert.equal(state.releases[0].source,'netlify');
  for(const fn of events.change)fn({target:{matches:s=>s==='[data-net-auto]',dataset:{netAuto:'fc27-tracker'},checked:true}});
  assert.equal(state.settings.netlifyAutoUpdateProjects['fc27-tracker'],true);
  site.metadata.version='1.75.5';site.metadata.changelog=['Melhoria A'];
  for(const fn of events.submit)fn({target:{id:'net-login'},preventDefault:()=>0});
  await flush();await flush();
  assert.equal(state.projects[0].version,'v1.75.5');
  assert.equal(state.releases.length,2);
  assert.match(state.releases[1].notes,/Melhoria A/);
  site.metadata.version='1.75.2';
  for(const fn of events.submit)fn({target:{id:'net-login'},preventDefault:()=>0});
  await flush();await flush();
  assert.equal(state.projects[0].version,'v1.75.5');
  assert.equal(state.releases.length,2);
  assert.ok(saves>=3);
});
